// Writes src/qeetrix/native-components.ts: Qeetrix for iOS's and Android's components, read from each
// library's docs/components.md at its release tag (nativeLibraries in src/qeetrix/packages.ts), each
// matched to the web component pages it stands for. The docs build can't see the native repositories,
// so the result is committed; after raising either version, run `bun run native` with both checked out
// beside this one (or pass their paths: bun run native <qeetrix-ios> <qeetrix-android>).
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import * as react from "@qeetrix/react";
import * as experimental from "@qeetrix/react/experimental";
import { DOCS } from "@/qeetrix/components/registry";
import { slug } from "@/qeetrix/docs/components";
import { nativeLibraries } from "@/qeetrix/packages";

const [iosRepo = "../qeetrix-ios", androidRepo = "../qeetrix-android"] = process.argv.slice(2);
// iOS tags are the bare version, Swift's convention; Android's carry a v.
const sources = {
  ios: { repo: iosRepo, tag: nativeLibraries.ios.version },
  android: { repo: androidRepo, tag: `v${nativeLibraries.android.version}` },
};

const read = (repo: string, tag: string) =>
  execFileSync("git", ["-C", repo, "show", `${tag}:docs/components.md`], { encoding: "utf8" });

/** The first table's rows (the component list), as cells; what follows it is prose. */
function table(markdown: string): string[][] {
  const lines = markdown.split("\n");
  const start = lines.findIndex((line) => line.startsWith("| Group |"));
  const rows: string[][] = [];
  for (const line of lines.slice(start + 2)) {
    if (!line.startsWith("|")) break;
    rows.push(
      line
        .slice(1, -1)
        .split(" | ")
        .map((cell) => cell.trim()),
    );
  }
  return rows;
}

/** The code names in a cell, in order: `QeetrixButton`, `.buttonStyle(.qeetrix())`; a parenthesis after a space is a note. */
const codes = (cell: string) =>
  [...(cell.split(" (")[0] ?? "").matchAll(/`([^`]+)`/g)].map((m) => m[1] ?? "");

const pascal = (name: string) =>
  name
    .split(" ")
    .map((w) => (w[0] ?? "").toUpperCase() + w.slice(1))
    .join("");
const exported = new Set([...Object.keys(react), ...Object.keys(experimental)]);

/**
 * The web names a cell gives as the counterpart: the capitalised names before any note ("Dialog with
 * Cancel…", "Drawer, as a bottom sheet", "Toast (`ToastProvider`)"); none when it says there's none.
 */
function webNames(cell: string): string[] {
  const text = cell.replaceAll("`", "");
  if (/^(—|none)/.test(text)) return [];
  const lead = (text.split(" (")[0] ?? "").split(" with ")[0] ?? "";
  return [...lead.matchAll(/\b[A-Z][A-Za-z0-9]*\b/g)].map((m) => m[0]);
}

/** A web name's page: by the page's own name or main export; else the one page that exports it. */
function pageOf(name: string): string | undefined {
  const own = DOCS.find((d) => pascal(d.name) === name || d.exports[0] === name);
  if (own) return own.slug;
  const all = DOCS.filter((d) => d.exports.includes(name));
  return all.length === 1 ? all[0]?.slug : undefined;
}

function components(platform: "ios" | "android") {
  const { repo, tag } = sources[platform];
  return table(read(repo, tag)).map((cells) => {
    const [group = "", name = "", api = "", ...rest] = cells;
    const web = rest.at(-1) ?? "";
    const names = webNames(web);
    // A component of the same name as a page is that page's, whatever the table's counterpart says.
    const pages = [
      ...new Set([...names.map(pageOf), DOCS.find((d) => d.slug === slug(name))?.slug]),
    ].filter((page): page is string => !!page);
    return {
      name,
      group: group.replace(/^\P{L}+/u, ""),
      api: codes(api),
      ...(platform === "android" ? { package: codes(rest[0] ?? "")[0] ?? "" } : {}),
      pages,
      web: names.filter((n) => exported.has(n)),
    };
  });
}

const ios = components("ios");
const android = components("android");
const notBuilt =
  /Not built, by decision: ([^.]+)\./.exec(read(sources.android.repo, sources.android.tag))?.[1] ??
  "";

const header = `// Generated by scripts/native-components.ts from docs/components.md in qeetrix-ios ${sources.ios.tag} and
// qeetrix-android ${sources.android.tag}: don't edit; raise the versions in packages.ts and run \`bun run native\`.

export interface NativeComponent {
  /** The native library's own name for it: "Segmented control". */
  name: string;
  /** Its group in the native list: "Actions". */
  group: string;
  /** Its API, as the native list writes it: QeetrixButton, .buttonStyle(.qeetrix()). */
  api: string[];
  /** Android only: its package, under com.qeetgroup.qeetrix.components. */
  package?: string;
  /** The web component pages it stands for, by slug; none for a component only native apps have. */
  pages: string[];
  /** The @qeetrix/react names the native list gives as its counterpart, where the package has them. */
  web: string[];
}
`;
const body = `
export const iosComponents: NativeComponent[] = ${JSON.stringify(ios, null, 2)};

export const androidComponents: NativeComponent[] = ${JSON.stringify(android, null, 2)};

/** What Qeetrix for Android leaves out on purpose, as its list says. */
export const androidNotBuilt = ${JSON.stringify(notBuilt)};
`;
writeFileSync(new URL("../src/qeetrix/native-components.ts", import.meta.url), header + body);
console.log(
  `iOS ${sources.ios.tag}: ${ios.length} components; Android ${sources.android.tag}: ${android.length}`,
);
